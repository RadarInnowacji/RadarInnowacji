  <h1>Zasady głosowania i prywatność</h1>

  <h2>Głosowanie</h2>
  <ul>
    <li>Głosować może każda osoba, która potwierdzi swój adres e-mail. Jedna osoba – jedno konto.</li>
    <li>Każda osoba może poprzeć maksymalnie <strong><?= votes_per_user() ?></strong> różne projekty, na każdy po jednym głosie. Oddanego głosu nie można przenieść.</li>
    <li>Organizator czuwa nad uczciwym przebiegiem głosowania. Głosy oddane niezgodnie z zasadami – np. z wielu kont jednej osoby lub w sposób zautomatyzowany – mogą zostać unieważnione, a konta zablokowane.</li>
    <li>Do wyników liczą się wyłącznie ważne głosy.</li>
  </ul>

  <h2>Zgłoszenia</h2>
  <ul>
    <li>Zgłaszać można inicjatywy szkół, uczelni, samorządów i innych instytucji publicznych.</li>
    <li>Każde zgłoszenie przechodzi moderację przed publikacją. Treści niezgodne z tematem, obraźliwe lub naruszające prawa osób trzecich zostaną odrzucone.</li>
  </ul>

  <h2 id="prywatnosc">Prywatność (RODO)</h2>
  <ul>
    <li>Przechowujemy Twój adres e-mail – służy do logowania i do kontaktu w sprawie zgłoszonego projektu.</li>
    <li>Dane techniczne połączenia (np. adres IP) przetwarzamy wyłącznie w postaci zanonimizowanej i tylko w celu zapewnienia bezpieczeństwa głosowania.</li>
    <li>Dane techniczne zostaną usunięte po zakończeniu kampanii i ogłoszeniu wyników.</li>
    <li>Nie używamy ciasteczek reklamowych ani analitycznych – jedynie ciasteczko niezbędne do logowania.</li>
  </ul>
